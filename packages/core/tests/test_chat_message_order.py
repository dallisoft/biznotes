"""채팅 메시지 순서 — 삽입 순번 `seq` (#4).

PostgreSQL `now()`는 트랜잭션 시작 시각이다. 한 트랜잭션에서 넣은 질문과 답변은
created_at이 같고, 트랜잭션이 겹치면 순서가 뒤집히기까지 한다. `seq`(IDENTITY)는
INSERT 순서대로 증가하므로 이것만으로 정렬한다. DB 없이 스키마 선언과 조회문의
정렬 키를 검증한다.
"""

import uuid
from typing import Any

from sqlalchemy import BigInteger
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from biznotes_core.models import ChatMessage, ChatSession


def test_seq_is_server_generated_identity():
    col = ChatMessage.__table__.c.seq

    assert isinstance(col.type, BigInteger)
    assert col.identity is not None
    assert col.nullable is False


def test_seq_ddl_on_postgresql():
    ddl = str(CreateTable(ChatMessage.__table__).compile(dialect=postgresql.dialect()))

    assert "seq BIGINT GENERATED BY DEFAULT AS IDENTITY" in ddl


def test_insert_leaves_seq_to_the_database():
    """애플리케이션이 seq를 채우지 않는다 — DB가 INSERT 순서대로 매긴다."""
    stmt = ChatMessage.__table__.insert().values(
        id=uuid.uuid4(), session_id=uuid.uuid4(), role="user", content="q"
    )

    assert "seq" not in str(stmt.compile(dialect=postgresql.dialect()))


class _Result:
    def __init__(self, rows: list[Any]) -> None:
        self._rows = rows

    def scalar_one_or_none(self) -> Any:
        return self._rows[0] if self._rows else None

    def scalars(self) -> "_Result":
        return self

    def all(self) -> list[Any]:
        return self._rows


class _RecordingDB:
    def __init__(self, session: ChatSession) -> None:
        self.session = session
        self.statements: list[Any] = []

    async def execute(self, stmt: Any) -> _Result:
        self.statements.append(stmt)
        if stmt.column_descriptions[0]["entity"] is ChatSession:
            return _Result([self.session])
        return _Result([])

